"""Render agents/shark-<slug>.md for every sourced profile. Stubs get no agent.

    python scripts/build_agents.py

Stats come from the full deal record here (this is the shipped agent, not a backtest).
Re-run after editing a profile or re-preparing data.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tank import PROCESSED, ROOT  # noqa: E402
from tank.columns import SHARKS  # noqa: E402
from tank.data import load_jsonl  # noqa: E402
from tank.profiles import load, sourced_slugs  # noqa: E402
from tank.prompt import MOVE_SCHEMA, schema_json, system_prompt  # noqa: E402
from tank.stats import shark_stats  # noqa: E402


def render(profile, stats):
    return "\n".join([
        "---",
        f"name: shark-{profile['slug']}",
        f"description: Investor model built from {profile['name']}'s public record (investor mode). "
        "Evaluates one pitch independently and returns a JSON verdict; in Tank mode returns one negotiation move. "
        "Invoked by the /tank skill.",
        "tools: Read",
        "---",
        "",
        "<!-- Generated by scripts/build_agents.py from sharks/"
        f"{profile['slug']}/profile.toml. Do not edit by hand. -->",
        "",
        system_prompt(profile, stats, negotiation=True),
        "",
        "## Verdict schema",
        "```json",
        schema_json(),
        "```",
        "",
        "## Move schema (Tank mode only)",
        "```json",
        json.dumps(MOVE_SCHEMA, indent=2),
        "```",
        "",
    ])


def main(processed=PROCESSED, agents_dir=ROOT / "agents"):
    if not Path(processed).exists():
        raise SystemExit(f"{processed} not found. Run scripts/prepare_data.py first.")
    records = load_jsonl(processed)
    agents_dir.mkdir(exist_ok=True)
    live = set(sourced_slugs())
    for slug in SHARKS:
        path = agents_dir / f"shark-{slug}.md"
        if slug in live:
            path.write_text(render(load(slug), shark_stats(records, slug)), encoding="utf-8")
            print(f"built   {path.name}")
        elif path.exists():
            path.unlink()
            print(f"removed {path.name} (profile is a stub)")
        else:
            print(f"skipped shark-{slug} (stub)")


if __name__ == "__main__":
    main()
